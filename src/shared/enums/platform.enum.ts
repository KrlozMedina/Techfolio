/**
 * Enum que representa las plataformas en las que un proyecto puede estar enfocado.
 * - WEB: Aplicaciones web accesibles desde navegadores.
 * - MOBILE: Aplicaciones móviles (iOS, Android).
 * - DESKTOP: Aplicaciones de escritorio (Windows, macOS, Linux).
 * - IOT: Dispositivos IoT conectados.
 * - INDUSTRIAL: Sistemas industriales o embebidos.
 */
export enum Platform {
  WEB = "Web",
  MOBILE = "Mobile",
  DESKTOP = "Desktop",
  IOT = "IOT",
  INDUSTRIAL = "Industrial",
}
